<script lang="ts">
  import { onMount, untrack } from "svelte";
  import {
    generateTargetKey,
    saveTargets,
    setTargetPassword,
    targetSecrets,
    type SftpTarget,
    type Target,
  } from "$lib/site";

  interface Props {
    siteRoot: string;
    /** All targets of the site; the edited one is at `index` (or new if -1). */
    targets: Target[];
    index: number;
    initial: SftpTarget;
    onsaved: (targets: Target[]) => void;
    oncancel: () => void;
  }

  let { siteRoot, targets, index, initial, onsaved, oncancel }: Props = $props();

  let form = $state(untrack(() => $state.snapshot(initial)));
  let password = $state("");
  let showPassword = $state(false);
  let hasPassword = $state(false);
  let publicKey = $state<string | null>(null);
  let copied = $state(false);
  let busy = $state(false);
  let error = $state<string | null>(null);

  // Secrets are stored per login (user, host, port); look them up when the
  // form opens.
  onMount(async () => {
    if (!form.host || !form.user) return;
    try {
      const status = await targetSecrets(form);
      hasPassword = status.has_password;
      publicKey = status.public_key;
    } catch (e) {
      error = String(e);
    }
  });

  let canGenerate = $derived(form.host.trim() !== "" && form.user.trim() !== "");

  async function generate() {
    busy = true;
    error = null;
    try {
      publicKey = await generateTargetKey(form);
    } catch (e) {
      error = String(e);
    } finally {
      busy = false;
    }
  }

  async function copy() {
    if (!publicKey) return;
    await navigator.clipboard.writeText(publicKey);
    copied = true;
  }

  async function save(event: SubmitEvent) {
    event.preventDefault();
    const target: SftpTarget = {
      ...form,
      name: form.name.trim(),
      host: form.host.trim(),
      user: form.user.trim(),
      path: form.path.trim(),
      port: Number(form.port) || 22,
    };
    if (targets.some((t, i) => i !== index && t.name === target.name)) {
      error = `There is already a target called ${target.name}.`;
      return;
    }
    // A different server means the old fingerprint doesn't apply.
    if (target.host !== initial.host || target.port !== initial.port) target.host_key = null;

    const updated = $state.snapshot(targets);
    if (index >= 0) updated[index] = target;
    else updated.push(target);

    busy = true;
    error = null;
    try {
      await saveTargets(siteRoot, updated);
      if (target.auth === "password" && password !== "") await setTargetPassword(target, password);
      onsaved(updated);
    } catch (e) {
      error = String(e);
    } finally {
      busy = false;
    }
  }
</script>

<form id="target-form" class="@container flex flex-col gap-4 rounded-box border border-base-300 p-4" onsubmit={save}>
  <h3 class="font-semibold">{index >= 0 ? `Edit ${initial.name}` : "New SFTP target"}</h3>

  <div class="grid gap-3 @2xl:grid-cols-[2fr_2fr_6rem]">
    <label class="flex flex-col gap-1">
      <span class="text-sm font-medium">Name</span>
      <input id="target-name" class="input w-full" bind:value={form.name} required placeholder="My webspace" />
    </label>
    <label class="flex flex-col gap-1">
      <span class="text-sm font-medium">Server</span>
      <input id="target-host" class="input w-full" bind:value={form.host} required placeholder="example.com" />
    </label>
    <label class="flex flex-col gap-1">
      <span class="text-sm font-medium">Port</span>
      <input id="target-port" class="input w-full" type="number" min="1" max="65535" bind:value={form.port} />
    </label>
    <label class="flex flex-col gap-1">
      <span class="text-sm font-medium">User</span>
      <input id="target-user" class="input w-full" bind:value={form.user} required autocomplete="off" />
    </label>
    <label class="flex flex-col gap-1 @2xl:col-span-2">
      <span class="text-sm font-medium">Folder on the server</span>
      <input id="target-path" class="input w-full" bind:value={form.path} required placeholder="/var/www/html" />
    </label>
  </div>

  <fieldset class="flex flex-col gap-3">
    <legend class="mb-2 text-sm font-medium">Log in with</legend>
    <div class="flex gap-6">
      <label class="flex items-center gap-2">
        <input type="radio" class="radio radio-sm" value="password" bind:group={form.auth} /> Password
      </label>
      <label class="flex items-center gap-2">
        <input type="radio" class="radio radio-sm" value="key" bind:group={form.auth} /> Key generated by qed
      </label>
    </div>

    {#if form.auth === "password"}
      <div class="flex max-w-md gap-2">
        <input id="target-password" class="input w-full" type={showPassword ? "text" : "password"} bind:value={password}
          autocomplete="new-password" spellcheck="false"
          placeholder={hasPassword ? "Saved in the keychain; type to replace" : "Password"} />
        <button type="button" class="btn btn-ghost" onclick={() => (showPassword = !showPassword)}>
          {showPassword ? "Hide" : "Show"}
        </button>
      </div>
    {:else}
      <div class="flex flex-col gap-2">
        {#if publicKey}
          <p class="text-sm text-base-content/70">
            Add this line to <code>~/.ssh/authorized_keys</code> on the server, or paste it into your hosting
            control panel's SSH keys:
          </p>
          <div class="flex items-start gap-2">
            <code id="target-public-key" class="flex-1 rounded-field bg-base-200 p-2 font-mono text-xs break-all">{publicKey}</code>
            <button type="button" class="btn btn-sm" onclick={copy}>{copied ? "Copied" : "Copy"}</button>
          </div>
        {/if}
        <div>
          <button type="button" id="generate-key" class="btn btn-sm" onclick={generate} disabled={!canGenerate || busy}>
            {publicKey ? "Generate a new key" : "Generate key"}
          </button>
          {#if !canGenerate}<span class="ms-2 text-sm text-base-content/60">Fill in server and user first.</span>{/if}
        </div>
      </div>
    {/if}
  </fieldset>

  {#if form.host_key}
    <div class="flex flex-wrap items-center gap-3 text-sm">
      <span class="text-base-content/70">Trusted server key:</span>
      <code class="font-mono break-all">{form.host_key}</code>
      <button type="button" id="forget-host-key" class="btn btn-ghost btn-xs" onclick={() => (form.host_key = null)}>
        Forget
      </button>
      <span class="w-full text-xs text-base-content/60">
        Only if the server was reinstalled or moved. The next connection test asks again.
      </span>
    </div>
  {/if}

  <label class="flex items-start gap-3">
    <input type="checkbox" class="toggle toggle-sm mt-0.5" bind:checked={form.delete_stale} />
    <span class="text-sm">
      Delete files that earlier publishes uploaded and the site no longer has.
      <span class="text-base-content/60">Files qed didn't upload are never touched.</span>
    </span>
  </label>

  {#if error}
    <div role="alert" class="alert alert-error alert-soft text-sm">{error}</div>
  {/if}

  <div class="flex justify-end gap-2">
    <button type="button" class="btn btn-ghost" onclick={oncancel}>Cancel</button>
    <button id="save-target" class="btn btn-primary" disabled={busy}>Save target</button>
  </div>
</form>
